import { storage } from "./firebase.js";
import { ref, uploadBytes, uploadString } from "firebase/storage";
import { resizeImage } from "./upload.js";

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const html = (str) => { const t = document.createElement("template"); t.innerHTML = str.trim(); return t.content.firstElementChild; };

/** Signature pad on a single canvas. returns { el, isEmpty(), clear(), dataUrl() } */
export function signaturePad(width = 600, height = 220) {
  const el = html(`<div class="sig"><canvas width="${width}" height="${height}"></canvas><div class="sig-tools"><span class="muted small">Sign inside the box with your finger</span><button type="button" class="sig-clear">Clear</button></div></div>`);
  const c = el.querySelector("canvas"), ctx = c.getContext("2d");
  ctx.lineWidth = 3; ctx.lineCap = "round"; ctx.lineJoin = "round"; ctx.strokeStyle = "#111";
  let drawing = false, empty = true;
  const pos = (e) => { const r = c.getBoundingClientRect(); const p = e.touches ? e.touches[0] : e; return [(p.clientX - r.left) * (c.width / r.width), (p.clientY - r.top) * (c.height / r.height)]; };
  const start = (e) => { drawing = true; empty = false; const [x, y] = pos(e); ctx.beginPath(); ctx.moveTo(x, y); e.preventDefault(); };
  const move = (e) => { if (!drawing) return; const [x, y] = pos(e); ctx.lineTo(x, y); ctx.stroke(); e.preventDefault(); };
  const end = () => (drawing = false);
  c.addEventListener("mousedown", start); c.addEventListener("mousemove", move); window.addEventListener("mouseup", end);
  c.addEventListener("touchstart", start, { passive: false }); c.addEventListener("touchmove", move, { passive: false }); c.addEventListener("touchend", end);
  el.querySelector(".sig-clear").onclick = () => { ctx.clearRect(0, 0, c.width, c.height); empty = true; };
  return { el, isEmpty: () => empty, clear: () => el.querySelector(".sig-clear").click(), dataUrl: () => c.toDataURL("image/png") };
}

/** Build the waiver PDF. returns Blob */
export async function buildWaiverPdf({ store, resv, waiverText, signerName, signatureDataUrl, idPhotoDataUrl, signedAt = new Date() }) {
  const { jsPDF } = await import("jspdf");
  const pdf = new jsPDF({ unit: "pt", format: "a4" });
  const W = pdf.internal.pageSize.getWidth(), M = 48;
  let y = M;
  pdf.setFont("helvetica", "bold"); pdf.setFontSize(16); pdf.text(store.name || "", M, y); y += 20;
  pdf.setFont("helvetica", "normal"); pdf.setFontSize(10); pdf.setTextColor(100);
  pdf.text([store.contact?.address, store.contact?.phone].filter(Boolean).join(" · "), M, y); y += 22;
  pdf.setTextColor(0); pdf.setFont("helvetica", "bold"); pdf.setFontSize(13); pdf.text("BOOKING WAIVER & AGREEMENT", M, y); y += 18;
  pdf.setFont("helvetica", "normal"); pdf.setFontSize(10);
  const kindLabel = { table: "Table reservation", event: "Event booking", vip: "VIP room booking", stay: "Stay booking" }[resv.kind] || "Reservation";
  const details = [
    `Reference: ${resv.code}    Type: ${kindLabel}`,
    `Name: ${resv.name}    Phone: ${resv.phone}`,
    `Date & time: ${resv.date} ${resv.time}${resv.endTime ? "–" + resv.endTime : ""}    Pax: ${resv.pax}`,
    resv.packageName ? `Package: ${resv.packageName}` : null, resv.roomName ? `Room: ${resv.roomName}${resv.hours ? ` (${resv.hours}h)` : ""}` : null,
    resv.estimate != null ? `Estimated amount: PHP ${Number(resv.estimate).toLocaleString()}${resv.deposit ? `    Deposit: PHP ${Number(resv.deposit).toLocaleString()}` : ""}` : null,
  ].filter(Boolean);
  details.forEach((l) => { pdf.text(l, M, y); y += 14; });
  y += 8; pdf.setDrawColor(180); pdf.line(M, y, W - M, y); y += 16;
  const lines = pdf.splitTextToSize(waiverText || "", W - 2 * M);
  lines.forEach((l) => { if (y > 760) { pdf.addPage(); y = M; } pdf.text(l, M, y); y += 13; });
  y += 16; if (y > 640) { pdf.addPage(); y = M; }
  pdf.setFont("helvetica", "bold"); pdf.text("Signature:", M, y); pdf.setFont("helvetica", "normal");
  if (signatureDataUrl) pdf.addImage(signatureDataUrl, "PNG", M, y + 6, 200, 73);
  y += 86; pdf.line(M, y, M + 220, y); y += 14;
  pdf.text(`${signerName}    Signed: ${signedAt.toLocaleString("en-PH", { dateStyle: "medium", timeStyle: "short" })}`, M, y); y += 20;
  if (idPhotoDataUrl) { if (y > 560) { pdf.addPage(); y = M; } pdf.setFont("helvetica", "bold"); pdf.text("ID presented:", M, y); y += 8; pdf.addImage(idPhotoDataUrl, "JPEG", M, y, 240, 160); y += 170; }
  pdf.setFontSize(8); pdf.setTextColor(120); pdf.text(`Generated by TapTayo · ${resv.code} · ${new Date().toISOString()}`, M, 812);
  return pdf.output("blob");
}

const blobToDataUrl = (b) => new Promise((res) => { const r = new FileReader(); r.onload = () => res(r.result); r.readAsDataURL(b); });

/** Full flow: sign → PDF → upload (customer path) → returns { pdfUrl, signatureUrl, idPhotoUrl } */
export async function signAndUploadWaiver({ storeId, uid, store, resv, waiverText, signerName, sigDataUrl, idFile }) {
  // Files go to the PRIVATE folder: not readable by URL, only through the privateFile function (staff or the customer).
  const base = `stores/${storeId}/private/${uid}`;
  let idPhotoDataUrl = null, idPhotoUrl = null;
  if (idFile) { const blob = await resizeImage(idFile, 900, 0.8); idPhotoDataUrl = await blobToDataUrl(blob); const path = `${base}/id-${resv.code}.jpg`; await uploadBytes(ref(storage, path), blob, { contentType: "image/jpeg" }); idPhotoUrl = `priv:${path}`; }
  const sigPath = `${base}/sig-${resv.code}.png`;
  await uploadString(ref(storage, sigPath), sigDataUrl, "data_url"); const signatureUrl = `priv:${sigPath}`;
  const pdfBlob = await buildWaiverPdf({ store, resv, waiverText, signerName, signatureDataUrl: sigDataUrl, idPhotoDataUrl });
  const pdfPath = `${base}/waiver-${resv.code}.pdf`;
  await uploadBytes(ref(storage, pdfPath), pdfBlob, { contentType: "application/pdf" }); const pdfUrl = `priv:${pdfPath}`;
  return { pdfUrl, signatureUrl, idPhotoUrl };
}

